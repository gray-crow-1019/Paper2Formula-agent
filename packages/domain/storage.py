import hashlib
from pathlib import Path

from .errors import DomainError


def file_hash(path: Path) -> str:
    with path.open("rb") as handle:
        digest = hashlib.file_digest(handle, "sha256")
    return digest.hexdigest()


class Storage:
    """Server-generated keys, with a local working cache for PDF tooling."""

    def __init__(self, settings):
        self.root = settings.storage_dir.resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        self.settings = settings
        self.client = None
        if settings.storage_backend == "s3":
            import boto3
            self.client = boto3.client("s3", endpoint_url=settings.s3_endpoint_url,
                                       aws_access_key_id=settings.s3_access_key,
                                       aws_secret_access_key=settings.s3_secret_key,
                                       region_name=settings.s3_region)

    def path(self, key: str) -> Path:
        target = (self.root / key).resolve()
        if not target.is_relative_to(self.root) or target == self.root:
            raise DomainError("INVALID_OBJECT_KEY", "非法存储路径")
        return target

    def key(self, path: Path) -> str:
        path = path.resolve()
        if not path.is_relative_to(self.root):
            raise DomainError("INVALID_OBJECT_KEY", "产物不在存储目录内")
        return path.relative_to(self.root).as_posix()

    def publish(self, path: Path) -> str:
        key = self.key(path)
        if self.client:
            self.client.upload_file(str(path), self.settings.s3_bucket, key)
        return key

    def fetch(self, key: str) -> Path:
        path = self.path(key)
        if not path.is_file() and self.client:
            path.parent.mkdir(parents=True, exist_ok=True)
            self.client.download_file(self.settings.s3_bucket, key, str(path))
        if not path.is_file():
            raise DomainError("MISSING_ARTIFACT", "文件已丢失", 404)
        return path

    def delete_document(self, document_id: str):
        # Only UUID-based document subdirectories generated by the server are accepted.
        import shutil
        import uuid
        uuid.UUID(document_id)
        directory = self.path(f"documents/{document_id}")
        if self.client:
            prefix = f"documents/{document_id}/"
            paginator = self.client.get_paginator("list_objects_v2")
            for page in paginator.paginate(Bucket=self.settings.s3_bucket, Prefix=prefix):
                keys = [{"Key": item["Key"]} for item in page.get("Contents", [])]
                if keys:
                    self.client.delete_objects(Bucket=self.settings.s3_bucket, Delete={"Objects": keys})
        if directory.is_dir():
            shutil.rmtree(directory)
